def get_category(text: str) -> tuple[str, str]:
    """
    پیدا کردن دسته‌بندی مناسب برای یک متن

    Returns:
        (نام دسته, ایموجی دسته)
    """
    text_lower = text.lower()
    for cat_name, cat_data in CATEGORIES.items():
        for kw in cat_data["keywords"]:
            if kw in text_lower:
                return cat_name, cat_data["emoji"]
    return "عمومی محیط زیست", "🌿"
